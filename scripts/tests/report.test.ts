import fs from 'node:fs';
import { makeSeed } from '../../shared/seed.ts';
import { reduce } from '../../shared/reducer.ts';
const out = process.argv[2] ?? '.';
let last: Blob | null = null;
(globalThis as any).document = { createElement: () => ({ click() {}, remove() {}, set href(_v: string) {}, set download(v: string) { (globalThis as any).__name = v; } }), body: { appendChild() {} } };
const origCreate = URL.createObjectURL;
URL.createObjectURL = (b: Blob) => { last = b; return 'blob:x'; };
(globalThis as any).fetch = async () => new Response(fs.readFileSync('web/public/apple-touch-icon.png'));
(globalThis as any).FileReader = class { result: string | null = null; onload: any; readAsDataURL(b: Blob) { b.arrayBuffer().then((ab) => { this.result = 'data:image/png;base64,' + Buffer.from(ab).toString('base64'); this.onload?.(); }); } };
const { downloadPdf, downloadXlsx } = await import('../../web/src/lib/reports.ts');
let s = makeSeed();
s = reduce(s, { type: 'expense/review', id: 'ex_002', status: 'approved', by: 'u_jordan' });
await downloadPdf(s, s.orgs[0], { preparedFor: 'Prof. Maren Olsen' });
fs.writeFileSync(`${out}/report.pdf`, Buffer.from(await last!.arrayBuffer()));
await downloadXlsx(s, s.orgs[0]);
fs.writeFileSync(`${out}/report.xlsx`, Buffer.from(await last!.arrayBuffer()));
URL.createObjectURL = origCreate;
console.log('ok');
